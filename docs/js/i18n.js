function flTranslate(lang, path) {
  const parts = path.split(".");
  let node = FL_TRANSLATIONS[lang] || FL_TRANSLATIONS.en;
  for (const part of parts) {
    if (!node) break;
    node = node[part];
  }
  return node ?? path;
}

function flApplyLanguage(lang) {
  if (!FL_TRANSLATIONS[lang]) lang = "en";

  document.documentElement.lang = FL_LANG_TAG[lang];

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = flTranslate(lang, el.getAttribute("data-i18n"));
  });

  document.querySelectorAll(".lang-select").forEach((select) => {
    select.value = lang;
  });

  try { localStorage.setItem("fl_lang", lang); } catch (e) { /* modo privado, sem problema */ }
}

function flInitLanguage() {
  let saved = "en";
  try { saved = localStorage.getItem("fl_lang") || "en"; } catch (e) { /* segue com o padrão */ }

  flApplyLanguage(saved);

  document.querySelectorAll(".lang-select").forEach((select) => {
    select.addEventListener("change", (event) => flApplyLanguage(event.target.value));
  });
}

document.addEventListener("DOMContentLoaded", flInitLanguage);